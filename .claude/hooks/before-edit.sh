#!/usr/bin/env bash
# Blocks edits to secrets, sqlc output and migrations that are already committed.
cd "$CLAUDE_PROJECT_DIR" || exit 0
file=$(jq -r '.tool_input.file_path // empty')
[ -n "$file" ] || exit 0
rel=${file#"$CLAUDE_PROJECT_DIR"/}

case "$rel" in
  .env.example|*/.env.example) ;;
  .env|.env.*|*/.env|*/.env.*)
    echo "Never write .env files. Document variables in .env.example instead." >&2
    exit 2 ;;
  internal/store/db/*)
    echo "internal/store/db is generated by sqlc. Edit internal/store/queries/*.sql and run make generate." >&2
    exit 2 ;;
  internal/store/migrations/*.sql)
    if git ls-files --error-unmatch -- "$rel" >/dev/null 2>&1; then
      echo "$rel is a committed migration; never edit it. Create a new one with:" >&2
      echo "go tool goose -dir internal/store/migrations create <name> sql" >&2
      exit 2
    fi ;;
esac
exit 0
