#!/usr/bin/env bash
# Tests for the Claude Code hooks in this directory. Every case runs against a throwaway git
# repo with no go.mod, Makefile or sqlc.yaml, so nothing touches the network or a cluster.
# Run: bash .claude/hooks/hooks_test.sh
set -u

here=$(cd "$(dirname "$0")" && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

repo="$tmp/repo"
mkdir -p "$repo/internal/store/migrations"
git -C "$repo" init -q
echo "-- +goose Up" >"$repo/internal/store/migrations/00001_init.sql"
git -C "$repo" add . && git -C "$repo" -c user.name=t -c user.email=t@t commit -qm init
export CLAUDE_PROJECT_DIR="$repo"

pass=0 fail=0
ok() { pass=$((pass + 1)); }
bad() { fail=$((fail + 1)); echo "FAIL: $*"; }

# run <name> <want-exit> <want-stderr-substring> <hook> <json-payload>
run() {
  local name=$1 want=$2 msg=$3 hook=$4 payload=$5 got err
  err=$(printf '%s' "$payload" | "$here/$hook" 2>&1 >/dev/null)
  got=$?
  if [ "$got" != "$want" ]; then
    bad "$name: exit $got, want $want ($err)"
  elif [ -n "$msg" ] && [[ "$err" != *"$msg"* ]]; then
    bad "$name: stderr \"$err\" lacks \"$msg\""
  else
    ok
  fi
}
cmd() { jq -nc --arg c "$1" '{tool_input: {command: $c}}'; }
file() { jq -nc --arg f "$repo/$1" '{tool_input: {file_path: $f}}'; }

# 1-2. Every hook is executable and accepts an empty payload.
for h in before-bash before-edit after-edit stop-check; do
  if [ -x "$here/$h.sh" ]; then ok; else bad "$h.sh is not executable"; fi
  run "$h no-op" 0 "" "$h.sh" '{}'
done

# 3-8. before-bash: state-changing kubectl/helm must name the kind context.
run "kubectl apply, no context" 2 "--context kind-heimdall" before-bash.sh "$(cmd 'kubectl apply -f x.yaml')"
run "kubectl apply, kind context" 0 "" before-bash.sh "$(cmd 'kubectl --context kind-heimdall apply -f x.yaml')"
run "kubectl delete, --context=" 0 "" before-bash.sh "$(cmd 'kubectl --context=kind-heimdall delete pod x')"
run "kubectl apply, other context" 2 "" before-bash.sh "$(cmd 'kubectl --context kind-other apply -f x')"
run "kubectl get" 0 "" before-bash.sh "$(cmd 'kubectl get pods')"
run "helm install, no context" 2 "--kube-context kind-heimdall" before-bash.sh "$(cmd 'helm install x y')"
run "helm install, kind context" 0 "" before-bash.sh "$(cmd 'helm install x y --kube-context kind-heimdall')"

# 9-12. before-edit: secrets, sqlc output and committed migrations are off limits.
run "edit .env" 2 ".env" before-edit.sh "$(file .env)"
run "edit web/.env.local" 2 ".env" before-edit.sh "$(file web/.env.local)"
run "edit sqlc output" 2 "generated by sqlc" before-edit.sh "$(file internal/store/db/x.go)"
run "edit committed migration" 2 "committed migration" before-edit.sh "$(file internal/store/migrations/00001_init.sql)"
run "write new migration" 0 "" before-edit.sh "$(file internal/store/migrations/00002_next.sql)"
run "edit Go source" 0 "" before-edit.sh "$(file internal/api/x.go)"
run "edit .env.example" 0 "" before-edit.sh "$(file .env.example)"

# 13. after-edit: skips tools whose setup does not exist yet.
run "Go edit without go.mod" 0 "" after-edit.sh "$(file x.go)"
run "query edit without sqlc.yaml" 0 "" after-edit.sh "$(file internal/store/queries/q.sql)"

# 14. stop-check: no recursion, nothing to run without a Makefile.
run "stop hook active" 0 "" stop-check.sh '{"stop_hook_active": true}'
echo "-- changed" >>"$repo/internal/store/migrations/00001_init.sql"
run "dirty tree, no Makefile" 0 "" stop-check.sh '{"stop_hook_active": false}'

# 15-16. settings.json: valid, portable, no one-off or overlapping permissions.
settings="$here/../settings.json"
if jq empty "$settings" 2>/dev/null; then ok; else bad "settings.json is not valid JSON"; fi
# "X", "X:*" and "X *" overlap: strip the wildcard suffix before looking for repeats.
dups=$(jq -r '.permissions.allow[]' "$settings" | sed -E 's/(:\*| \*)\)$/)/' | sort | uniq -d)
if [ -z "$dups" ]; then ok; else bad "overlapping allow entries: $dups"; fi
if ! grep -q 'sed -i' "$settings"; then ok; else bad "settings.json has a one-off sed -i entry"; fi
if ! grep -q '/Users/' "$settings"; then ok; else bad "settings.json has a machine-specific path"; fi
if [ "$(jq '.permissions | has("additionalDirectories")' "$settings")" = false ]; then ok; else
  bad "settings.json has additionalDirectories"
fi

# 17-18. gh: reads run without a prompt, every write asks.
gh_allow=$(jq -r '.permissions.allow[] | select(startswith("Bash(gh"))' "$settings")
writes=$(printf '%s\n' "$gh_allow" |
  grep -E '^Bash\(gh( [a-z-]+)?( \*|:\*)\)$|gh api|create|edit|close|comment|delete|merge|reopen')
if [ -z "$writes" ]; then ok; else bad "allow entries cover gh writes: $writes"; fi
for read in "gh issue view:*" "gh issue list:*" "gh label list:*"; do
  if printf '%s\n' "$gh_allow" | grep -qxF "Bash($read)"; then ok; else bad "gh read not allowed: $read"; fi
done

echo "$pass passed, $fail failed"
[ "$fail" -eq 0 ]
